def sizes_js(lst):
    parts = []
    for label, price, cal in lst:
        parts.append('{l:"%s",p:%s,c:"%s"}' % (label, price, cal))
    return '[' + ','.join(parts) + ']'

changed_ids = []
for i, line in enumerate(lines):
    m = re.match(r'^\s*\{id:(\d+),', line)
    if not m:
        continue
    pid = int(m.group(1))
    if pid not in descs:
        continue
    # Replace desc:"..." (non-greedy up to next ',img:' or ',featured:' etc — desc always followed by ,img:)
    new_desc = descs[pid].replace('\\', '\\\\').replace('"', '\\"')
    line2 = re.sub(r'desc:"(?:[^"\\]|\\.)*"', 'desc:"%s"' % new_desc, line, count=1)
    # Replace sizes:[...] at end of line (before closing }, possibly followed by },\n or }];\n)
    new_sizes = sizes_js(sizes[pid])
    line2 = re.sub(r'sizes:\[.*\]\}', 'sizes:%s}' % new_sizes, line2, count=1)
    lines[i] = line2
    changed_ids.append(pid)

print("changed:", changed_ids)

